const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { createRequire } = require('node:module');
const root = "D:/骏冠/新媒体/video-remix-ai-assistant-full";
const req = createRequire(path.join(root, 'package.json'));
const asar = req('@electron/asar');
const fuses = req('@electron/fuses');
const yaml = req('js-yaml');
const archive = path.join(root, 'release/win-unpacked/resources/app.asar');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const extract = name => asar.extractFile(archive, name.split("/").join(path.sep));
const read = name => fs.readFileSync(path.join(root, name));
const walk = directory => fs.readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap(entry => {
  const file = directory + '/' + entry.name; return entry.isDirectory() ? walk(file) : [file];
});
(async () => {
  const metadata = JSON.parse(extract('package.json'));
  assert.equal(metadata.version, '1.0.21'); assert.equal(metadata.authMode, 'remote');
  const list = asar.listPackage(archive).map(file => file.replaceAll('\\', '/'));
  assert.equal(list.some(file => /^\/dist-electron\/services\/authService\.js(?:\.map)?$/.test(file)), false);
  const comparedFiles = [...walk('dist'), ...walk('dist-electron')].filter(file => !/^dist-electron\/services\/authService\.js(?:\.map)?$/.test(file)).map(file => {
    const local = read(file); const packaged = extract(file);
    assert.equal(hash(packaged), hash(local), '打包文件与构建不同：' + file);
    return { file, sha256: hash(packaged) };
  });
  assert.deepEqual(extract('dist-electron/services/desktopAuth.js'), extract('dist-electron/services/employeeAuth.js'));
  const remoteAuth = extract('dist-electron/services/remoteAuthService.js').toString('utf8');
  for (const value of ['auth.verification-retry', 'auth.request-completed', 'auth.request-failed', 'retry', '250']) assert.ok(remoteAuth.includes(value), '缺少授权修复 ' + value);
  const authConfig = JSON.parse(extract('dist-electron/auth-config.json'));
  assert.equal(authConfig.url, 'https://114.132.186.95');
  const providerConfig = extract('dist-electron/services/providerConfig.js').toString('utf8');
  for (const value of ['glm-image', 'agnes-image-2.5-flash', 'doubao-seedream-5-0-pro-260628']) assert.ok(providerConfig.includes(value), '缺少厂商模型 ' + value);
  const imageService = extract('dist-electron/services/imageGenerationService.js').toString('utf8');
  assert.ok(imageService.includes('GLM_SIZES') && imageService.includes('IMAGE_UNSUPPORTED') && imageService.includes('GET'));
  const renderer = comparedFiles.filter(file => /^dist\/assets\/.*\.js$/.test(file.file)).map(file => extract(file.file).toString('utf8')).join('\n');
  for (const label of ['Agnes', 'Seedream', 'GLM', 'glm-image-limits', '删除当前图']) assert.ok(renderer.includes(label), '缺少界面内容 ' + label);
  assert.equal(renderer.includes('Agnes 兼容'), false); assert.equal(renderer.includes('Seedream 兼容'), false);
  assert.equal(renderer.includes('测试生成图片'), false); assert.equal(renderer.includes('测试内容提取'), false);
  assert.equal(list.some(file => /(?:^|\/)(?:providers\.encrypted|(?:database|remix|app)\.(?:db|sqlite)|\.env|SSH\.key)$/.test(file)), false);
  const beforeInputs = JSON.parse(read('release/build-inputs-1.0.21.json')).files;
  const inputChanges = beforeInputs.filter(file => hash(read(file.file)) !== file.sha256);
  const verificationScriptChanges = inputChanges.filter(file => file.file === 'scripts/providerSettingsSmoke.cjs');
  const buildInputChanges = inputChanges.filter(file => file.file !== 'scripts/providerSettingsSmoke.cjs');
  assert.deepEqual(buildInputChanges, [], '打包期间产品源码发生变化');
  const wire = await fuses.getCurrentFuseWire(path.join(root, 'release/win-unpacked/video-remix-ai-assistant.exe'));
  const expected = { RunAsNode: 48, EnableNodeOptionsEnvironmentVariable: 48, EnableNodeCliInspectArguments: 48, EnableEmbeddedAsarIntegrityValidation: 49, OnlyLoadAppFromAsar: 49 };
  for (const [option, state] of Object.entries(expected)) assert.equal(wire[fuses.FuseV1Options[option]], state, '运行配置不匹配：' + option);
  const installerFile = 'video-remix-universal-setup-1.0.21.exe';
  const installerBytes = read('release/' + installerFile);
  assert.equal(installerBytes.subarray(0,2).toString(), 'MZ');
  const manifest = yaml.load(read('release/latest.yml').toString('utf8'));
  const sha512 = crypto.createHash('sha512').update(installerBytes).digest('base64');
  assert.equal(manifest.version, '1.0.21'); assert.equal(manifest.path, installerFile); assert.equal(manifest.sha512, sha512);
  const manifestFile = manifest.files.find(file => file.url === installerFile);
  assert.ok(manifestFile); assert.equal(manifestFile.sha512, sha512); assert.equal(manifestFile.size, installerBytes.length);
  const record = { authorizationRetryAndDiagnosticsIncluded: true, version: metadata.version, authMode: metadata.authMode, remoteEntryMatches: true, localAuthExcluded: true, productionAuthConfigMatches: true, threeImageProvidersIncluded: true, glmDownloadAndLimitsIncluded: true, providerSettingsIncluded: true, removedPaidTestButtons: true, rendererMatchesBuild: true, businessDataAbsent: true, comparedFiles, fuseWire: wire, buildInputCount: beforeInputs.length, buildInputChanges, verificationScriptChanges, asarSha256: hash(read('release/win-unpacked/resources/app.asar')), installer: { file: installerFile, bytes: installerBytes.length, MiB: Number((installerBytes.length/1024/1024).toFixed(1)), sha256: hash(installerBytes), sha512 }, updateManifestMatches: true, checkedAt: new Date().toISOString() };
  fs.writeFileSync(path.join(root, 'release/package-content-1.0.21.json'), JSON.stringify(record, null, 2) + '\n', 'utf8');
  console.log(JSON.stringify({ passed: true, version: record.version, comparedFiles: comparedFiles.length, buildInputs: beforeInputs.length, bytes: record.installer.bytes, sha256: record.installer.sha256 }));
})().catch(error => { console.error(error); process.exitCode = 1; });
